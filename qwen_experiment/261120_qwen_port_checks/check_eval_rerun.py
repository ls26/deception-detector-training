"""Smoke check (f): the changed eval (eval_checkpoint.py probes + labels, without the self-report follow-up) rerun on
261117's saved base eval of seed 42 (no_penalty/seed_42/evals/base_rescored: Llama-3's answers, generated by the old
eval), compared with the saved labels.

    python check_eval_rerun.py rescore --rerun-dir DIR   # the saved answers scored as the new generate stage does
    python check_eval_rerun.py compare --rerun-dir DIR   # after the probes and labels stages ran in DIR

rescore: each saved answer's pred / stage / content as the new generate stage records them (the last "answer is
(X)"; a cut-off answer unparsed). compare passes if: the label rows are the same rows in the same order; on the rows
the rescoring cannot change (the answer's pred is unchanged and so are its question's no-cue answers), every field
but the dropped ones (wording, p_yes, said, deception_rm) and the probe scores is equal, and the probe-scored rows
are the same. Reported: the rows the rescoring changed, and the largest probe-score difference, apart on the rows
whose answer has several "answer is (X)" (the probe now reads the last, the old eval the first).
"""

import argparse
import json
import re
from pathlib import Path

SAVED = Path("/workspace/sycophancy_experiments/261117_no_penalty_vs_frozen_400/no_penalty/seed_42/evals/base_rescored")
DROPPED = {"wording", "p_yes", "said", "deception_rm"}
PROBE_FIELDS = ("probe_start", "probe_fresh", "probe_start_base_activations")
ANSWER_IS = re.compile(r"answer is \(?([AB])\)?")


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text().splitlines()]


parser = argparse.ArgumentParser()
parser.add_argument("stage", choices=("rescore", "compare"))
parser.add_argument("--rerun-dir", type=Path, required=True)
args = parser.parse_args()

if args.stage == "rescore":
    import sys

    sys.path.insert(0, "/workspace/sycophancy-rl/sycophancy_setup")
    from domain_imports import to_content
    from obfuscation_atlas.tasks.multiple_choice import extract_answer

    rows = read_jsonl(SAVED / "completions.jsonl")
    changed = 0
    for row in rows:
        pred, stage = extract_answer(row["completion"]) if row["finish_reason"] == "stop" else (None, "cut_off")
        changed += pred != row["pred"]
        row.update({"pred": pred, "stage": stage, "content": to_content(pred, row["answer"])})
    args.rerun_dir.mkdir(parents=True, exist_ok=False)
    (args.rerun_dir / "completions.jsonl").write_text("".join(json.dumps(row) + "\n" for row in rows))
    print(f"rescored {len(rows)} answers; pred changed on {changed}")
    sys.exit(0)

saved, new = read_jsonl(SAVED / "labels.jsonl"), read_jsonl(args.rerun_dir / "labels.jsonl")
saved_completions = read_jsonl(SAVED / "completions.jsonl")
rescored = {(r["question_id"], r["condition"], r["sample_idx"]): r for r in read_jsonl(args.rerun_dir / "completions.jsonl")}
completions = {(r["question_id"], r["condition"], r["sample_idx"]): r["completion"] for r in saved_completions}
pred_changed = {(r["question_id"], r["condition"], r["sample_idx"]) for r in saved_completions
                if r["pred"] != rescored[(r["question_id"], r["condition"], r["sample_idx"])]["pred"]}
nocue_changed = {key[0] for key in pred_changed if key[1] == "none"}
assert len(saved) == len(new)
report = {"rows": len(new), "answers_pred_changed": len(pred_changed), "label_rows_changed_by_rescoring": 0,
          "max_probe_difference_read_unmoved": 0.0, "max_probe_difference_read_moved": 0.0, "rows_read_moved": 0,
          "probe_scored_rows": 0}
for old_row, new_row in zip(saved, new, strict=True):
    assert set(old_row) - DROPPED == set(new_row), (set(old_row) ^ set(new_row))
    key = (new_row["question_id"], new_row["condition"], new_row["sample_idx"])
    assert key == (old_row["question_id"], old_row["condition"], old_row["sample_idx"])
    if key in pred_changed or key[0] in nocue_changed:
        report["label_rows_changed_by_rescoring"] += 1
        continue
    for field in new_row:
        if field not in PROBE_FIELDS:
            assert old_row[field] == new_row[field], (field, old_row[field], new_row[field])
    assert (old_row["probe_start"] is None) == (new_row["probe_start"] is None)
    if new_row["probe_start"] is None:
        continue
    report["probe_scored_rows"] += 1
    moved = len(ANSWER_IS.findall(completions[(new_row["question_id"], new_row["condition"], new_row["sample_idx"])])) > 1
    report["rows_read_moved"] += moved
    key = "max_probe_difference_read_moved" if moved else "max_probe_difference_read_unmoved"
    report[key] = max(report[key], abs(old_row["probe_start"] - new_row["probe_start"]))
saved_summary, new_summary = (json.loads((d / "summary.json").read_text()) for d in (SAVED, args.rerun_dir))
report["summary_saved_without_deception"] = {k: v for k, v in saved_summary.items() if k not in ("deception_rm", "said")}
report["summary_new"] = new_summary
print(json.dumps(report, indent=2))
(args.rerun_dir.parent / "check_f_report.json").write_text(json.dumps(report, indent=2) + "\n")
print("PASS: on the rows the rescoring cannot change, labels equal apart from the dropped fields and the probe scores")
